def _info(user: str) -> dict[str, str]:
    match = re.search(r"创作信息（JSON）：(\{.*?\})\n", user)
    return json.loads(match.group(1)) if match else {}


@register_mock("lyrics")
def mock_lyrics(system: str, user: str) -> object:
    info = _info(user)
    presets = load_presets()
    theme_id = next((item.id for item in presets.themes if item.name == info.get("主题")), "daily")
    rap = info.get("音乐风格") == next(item.name for item in presets.styles if item.id == "rap")
    bank = RAP if rap else SONG
    chosen = bank.get(theme_id, bank["daily"])
    types = {"story": "narrative", "emotion": "emotional", "imagery": "imagery"}
    return {"variants": [
        {"type": types[approach], "title": title, "lyrics": text}
        for approach, (title, text) in chosen.items()
    ]}
